import Link from "next/link";
import { redirect } from "next/navigation";
import { currentProfile } from "@/lib/session";
import { visitSummary, SPECIALTIES, ageOf } from "@/lib/visit";
import { FlagBadge, fmt, range, GROUP_LABEL } from "@/components/Cards";
import PrintButton from "@/components/PrintButton";

export default async function VisitPage({ searchParams }: { searchParams: Promise<{ s?: string }> }) {
  const { profile } = await currentProfile();
  if (!profile) redirect("/");
  const s = (await searchParams).s ?? "general";
  const v = visitSummary(profile.id, s);
  const age = ageOf(profile.dob);
  const groups = [...new Set(v.rows.map((r) => r.group))];

  return (
    <div className="space-y-4">
      <div className="no-print space-y-2">
        <h1 className="text-xl font-semibold text-slate-900">Doctor visit summary</h1>
        <p className="text-sm text-slate-600">One page for your doctor, focused on what that specialist looks at. Print it or save it as a PDF.</p>
        <div className="flex flex-wrap gap-2" role="tablist">
          {Object.entries(SPECIALTIES).map(([k, x]) => (
            <Link key={k} href={`?s=${k}`} role="tab" aria-selected={k === s} className={`rounded-full border px-3 py-1 text-sm ${k === s ? "border-teal-700 bg-teal-700 text-white" : "border-slate-300 bg-white"}`}>{x.label}</Link>
          ))}
        </div>
        <PrintButton />
      </div>

      <article className="rounded-2xl border border-slate-200 bg-white p-5 print:border-0 print:p-0" data-testid="visit-summary">
        <header className="flex flex-wrap justify-between gap-2 border-b border-slate-200 pb-3">
          <div>
            <h2 className="text-lg font-semibold">{profile.name.replace(/\s*\(demo.*\)/, "")}</h2>
            <p className="text-sm text-slate-600">{[age != null && `${age} y`, profile.sex].filter(Boolean).join(" · ")}</p>
          </div>
          <div className="text-right text-sm text-slate-600">
            <p>For: <b>{v.spec.label}</b></p>
            <p>Prepared {new Date().toLocaleDateString()}</p>
          </div>
        </header>

        <h3 className="mt-4 font-semibold">Current medicines</h3>
        {v.meds.length ? (
          <ul className="mt-1 grid gap-x-6 text-sm sm:grid-cols-2">{v.meds.map((m) => <li key={m.full} title={m.full}>• {m.name} {m.dose && <span className="text-slate-500">{m.dose}</span>} <span className="text-xs text-slate-500">since {m.since?.slice(0, 7)}</span></li>)}</ul>
        ) : <p className="text-sm text-slate-500">None recorded.</p>}
        {v.stopped.length > 0 && <p className="mt-1 text-xs text-slate-600">Stopped in last 12 months: {v.stopped.map((m) => `${m.name} (${m.stopped})`).join(", ")}</p>}

        {groups.map((g) => (
          <section key={g} className="mt-4 break-inside-avoid">
            <h3 className="font-semibold">{GROUP_LABEL[g]}</h3>
            <table className="mt-1 w-full text-sm">
              <thead><tr className="text-left text-xs text-slate-500"><th>Test</th><th className="text-right">Latest</th><th className="hidden text-right sm:table-cell print:table-cell">Previous</th><th className="text-right">Range</th><th className="text-right">Status</th></tr></thead>
              <tbody>
                {v.rows.filter((r) => r.group === g).map((r) => (
                  <tr key={r.code} className="border-t border-slate-100">
                    <td className="py-1">{r.name}</td>
                    <td className="text-right tabular-nums"><b>{fmt(r.value)}</b> <span className="text-xs text-slate-500">{r.unit}</span><div className="text-[10px] text-slate-500">{r.date}</div></td>
                    <td className="hidden text-right tabular-nums text-slate-600 sm:table-cell print:table-cell">{r.prev ? <>{fmt(r.prev.value)} {r.prev.value < r.value ? "↑" : r.prev.value > r.value ? "↓" : "="}<div className="text-[10px]">{r.prev.date}</div></> : "—"}</td>
                    <td className="text-right text-xs text-slate-500">{range(r.low, r.high)}</td>
                    <td className="text-right"><FlagBadge f={r.flag} /></td>
                  </tr>
                ))}
              </tbody>
            </table>
          </section>
        ))}
        {!groups.length && <p className="mt-4 text-sm text-slate-500">No results in these areas yet.</p>}

        {v.other.length > 0 && (
          <section className="mt-4">
            <h3 className="font-semibold">Other out-of-range results</h3>
            <ul className="text-sm">{v.other.map((o) => <li key={o.name}>• {o.name}: {fmt(o.value)} {o.unit} ({o.date})</li>)}</ul>
          </section>
        )}
        <p className="mt-5 border-t border-slate-200 pt-2 text-[11px] text-slate-500">Generated by Vitalis from the patient&apos;s own uploaded records. Values as reported by labs, not interpreted. Not a diagnosis.</p>
      </article>
    </div>
  );
}
